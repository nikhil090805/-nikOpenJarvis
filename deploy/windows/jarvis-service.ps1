<#
.SYNOPSIS
    Register / unregister the OpenJarvis Windows scheduled task.

.DESCRIPTION
    The Windows equivalent of deploy/systemd/openjarvis.service and
    deploy/launchd/com.openjarvis.plist.

    Registers a per-user scheduled task named "OpenJarvis" that starts
    `jarvis serve` at logon and restarts on failure. Loopback default
    (127.0.0.1) so no API key is required — matches launchd parity.

    Security notes:
      * ListenHost/ListenPort are validated before they are used to build
        scheduled-task arguments; no unvalidated string reaches the task.
      * A non-loopback bind still requires OPENJARVIS_API_KEY, but the key is
        NOT persisted in a plaintext user environment variable. It is stored
        in a DPAPI-protected file readable only by this user, and injected
        into the server process by a small local launcher script.
      * The task runs with RunLevel Limited / LogonType Interactive.
      * The launcher is invoked with -ExecutionPolicy RemoteSigned, not
        Bypass, because it is a local file generated by this script.

    Subcommands:
      install   — create or replace the task
      uninstall — remove the task and its generated launcher/key files
      status    — show task state
      start     — start the task now
      stop      — stop the task

    Arguments (install only):
      -InstallRoot <path>  default: %LOCALAPPDATA%\OpenJarvis (matches
                           install.ps1's default)
      -ListenHost <addr>   default: 127.0.0.1 (loopback). Set to a non-loopback
                           address ONLY if you also set $env:OPENJARVIS_API_KEY.
      -ListenPort <int>    default: 8000 (valid range 1-65535)

    Usage:
      powershell -ExecutionPolicy RemoteSigned -File jarvis-service.ps1 install
      powershell -ExecutionPolicy RemoteSigned -File jarvis-service.ps1 status
      powershell -ExecutionPolicy RemoteSigned -File jarvis-service.ps1 start
      powershell -ExecutionPolicy RemoteSigned -File jarvis-service.ps1 stop
      powershell -ExecutionPolicy RemoteSigned -File jarvis-service.ps1 uninstall
#>

[CmdletBinding()]
param(
    [Parameter(Position = 0)]
    [ValidateSet('install', 'uninstall', 'status', 'start', 'stop')]
    [string] $Command = 'status',

    [string] $InstallRoot,

    [ValidatePattern('^[A-Za-z0-9.:\[\]-]+$')]
    [string] $ListenHost = '127.0.0.1',

    [ValidateRange(1, 65535)]
    [int] $ListenPort = 8000
)

$ErrorActionPreference = 'Stop'
$TaskName = 'OpenJarvis'

function Write-Info  ($msg) { Write-Host "[info]  $msg" -ForegroundColor Cyan }
function Write-Ok    ($msg) { Write-Host "[ok]    $msg" -ForegroundColor Green }
function Write-Warn2 ($msg) { Write-Host "[warn]  $msg" -ForegroundColor Yellow }
function Write-Fail  ($msg) {
    Write-Host "[fail]  $msg" -ForegroundColor Red
    exit 1
}

function Get-DefaultInstallRoot {
    if ($script:InstallRoot) { return $script:InstallRoot }
    if ($env:OPENJARVIS_HOME) { return $env:OPENJARVIS_HOME }
    return (Join-Path $env:LOCALAPPDATA 'OpenJarvis')
}

function ConvertTo-PsSingleQuoted {
    param([string] $Value)
    return "'" + $Value.Replace("'", "''") + "'"
}

# ValidatePattern above already rejects whitespace, quotes and shell
# metacharacters. This adds an IP-level check so only real addresses (or the
# literal "localhost") can reach the scheduled-task arguments.
function Resolve-ListenHost {
    param([string] $HostName)
    if ($HostName -ieq 'localhost') { return '127.0.0.1' }
    $parsed = [System.Net.IPAddress]::None
    if (-not [System.Net.IPAddress]::TryParse($HostName, [ref]$parsed)) {
        Write-Fail "ListenHost '$HostName' is not a valid IP address or 'localhost'."
    }
    return $HostName
}

function Test-LoopbackHost {
    param([string] $HostName)
    if ($HostName -ieq 'localhost') { return $true }
    $parsed = [System.Net.IPAddress]::None
    if (-not [System.Net.IPAddress]::TryParse($HostName, [ref]$parsed)) { return $false }
    return [System.Net.IPAddress]::IsLoopback($parsed)
}

function Assert-SafePath {
    param([string] $Path)
    if (-not $Path) { return }
    if ($Path -match '["\r\n&|;]') {
        Write-Fail "Paths containing quotes, newlines or shell metacharacters are not supported: $Path"
    }
}

function Get-ServicePaths {
    param([string] $Root)
    $dir = Join-Path $Root 'service'
    return @{
        Dir      = $dir
        KeyFile  = (Join-Path $dir 'api-key.dpapi')
        Launcher = (Join-Path $dir 'start-server.ps1')
    }
}

# ---------------------------------------------------------------------------
# install
# ---------------------------------------------------------------------------

function Install-Task {
    $root = Get-DefaultInstallRoot
    Assert-SafePath $root
    $srcDir = Join-Path $root 'src'
    Assert-SafePath $srcDir
    if (-not (Test-Path $srcDir)) {
        Write-Fail "OpenJarvis source not found at $srcDir. Run install.ps1 first."
    }

    $listen = Resolve-ListenHost $ListenHost
    Write-Info "  Listen  : $listen`:$ListenPort"
    $isLoopback = Test-LoopbackHost $listen

    if (-not $isLoopback -and -not $env:OPENJARVIS_API_KEY) {
        Write-Fail @"
ListenHost is $listen (non-loopback) but `$env:OPENJARVIS_API_KEY is
not set. An unauthenticated non-loopback bind is refused by jarvis serve
and would also create a security hole. Set the env var first:

    `$env:OPENJARVIS_API_KEY = (uv run jarvis auth generate-key)

then re-run with -ListenHost $listen.
"@
    }

    $uvCmd = Get-Command uv -ErrorAction SilentlyContinue
    if (-not $uvCmd) {
        $uvFallback = Join-Path $env:USERPROFILE '.local\bin\uv.exe'
        if (Test-Path $uvFallback) {
            $uvPath = $uvFallback
        } else {
            Write-Fail "uv.exe not found on PATH or at $uvFallback. Re-run install.ps1."
        }
    } else {
        $uvPath = $uvCmd.Source
    }
    Assert-SafePath $uvPath

    $paths = Get-ServicePaths $root
    if (-not (Test-Path $paths.Dir)) {
        New-Item -ItemType Directory -Path $paths.Dir -Force | Out-Null
    }

    # DPAPI encrypts to the current Windows user. The scheduled task runs as
    # that same least-privileged user, so it can decrypt; other users cannot.
    # Nothing is written to the User environment in plaintext.
    $useKeyFile = $false
    if (-not $isLoopback) {
        Write-Info "Storing the API key in a DPAPI-protected file for the scheduled task."
        $secure = ConvertTo-SecureString $env:OPENJARVIS_API_KEY -AsPlainText -Force
        $encrypted = ConvertFrom-SecureString $secure
        Set-Content -LiteralPath $paths.KeyFile -Value $encrypted -Encoding ASCII
        # Best-effort ACL hardening on top of DPAPI; the folder is already
        # under %LOCALAPPDATA% and therefore user-private by default.
        try {
            & icacls $paths.KeyFile /inheritance:r /grant:r "$($env:USERNAME):(F)" | Out-Null
        } catch {
            Write-Warn2 "  Could not tighten the key file ACL (DPAPI encryption still applies)."
        }
        $useKeyFile = $true
    }

    $launcherContent = @'
$ErrorActionPreference = 'Stop'
$uvPath      = __UV_PATH__
$srcDir      = __SRC_DIR__
$listenHost  = __LISTEN_HOST__
$listenPort  = __LISTEN_PORT__
$useKeyFile  = __USE_KEY_FILE__
$keyFile     = __KEY_FILE__

if ($useKeyFile -and (Test-Path -LiteralPath $keyFile)) {
    $secure = ConvertTo-SecureString ((Get-Content -LiteralPath $keyFile -Raw).Trim())
    $bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure)
    try {
        $env:OPENJARVIS_API_KEY = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr)
    } finally {
        [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr)
    }
}

Set-Location -LiteralPath $srcDir
& $uvPath run jarvis serve --host $listenHost --port $listenPort
exit $LASTEXITCODE
'@
    $launcherContent = $launcherContent.Replace('__UV_PATH__', (ConvertTo-PsSingleQuoted $uvPath))
    $launcherContent = $launcherContent.Replace('__SRC_DIR__', (ConvertTo-PsSingleQuoted $srcDir))
    $launcherContent = $launcherContent.Replace('__LISTEN_HOST__', (ConvertTo-PsSingleQuoted $listen))
    $launcherContent = $launcherContent.Replace('__LISTEN_PORT__', [string]$ListenPort)
    $launcherContent = $launcherContent.Replace('__USE_KEY_FILE__', $(if ($useKeyFile) { '$true' } else { '$false' }))
    $launcherContent = $launcherContent.Replace('__KEY_FILE__', (ConvertTo-PsSingleQuoted $paths.KeyFile))
    Set-Content -LiteralPath $paths.Launcher -Value $launcherContent -Encoding ASCII

    Write-Info "Registering scheduled task '$TaskName'..."
    Write-Info "  Working dir : $srcDir"
    Write-Info "  User        : $env:USERNAME"

    $existing = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
    if ($existing) {
        Write-Info "Existing task found — replacing."
        Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
    }

    $powershellExe = Join-Path $env:WINDIR 'System32\WindowsPowerShell\v1.0\powershell.exe'
    # Only validated values reach this string. The launcher path is quoted and
    # Assert-SafePath rejected quotes/metacharacters in the install root.
    $taskArguments = '-NoLogo -NoProfile -NonInteractive -ExecutionPolicy RemoteSigned -File "' + $paths.Launcher + '"'
    $action = New-ScheduledTaskAction `
        -Execute $powershellExe `
        -Argument $taskArguments `
        -WorkingDirectory $srcDir

    $trigger = New-ScheduledTaskTrigger -AtLogOn -User $env:USERNAME

    $settings = New-ScheduledTaskSettingsSet `
        -AllowStartIfOnBatteries `
        -DontStopIfGoingOnBatteries `
        -StartWhenAvailable `
        -RestartCount 3 `
        -RestartInterval (New-TimeSpan -Minutes 1) `
        -ExecutionTimeLimit (New-TimeSpan -Seconds 0)

    $principal = New-ScheduledTaskPrincipal `
        -UserId $env:USERNAME `
        -LogonType Interactive `
        -RunLevel Limited

    Register-ScheduledTask `
        -TaskName $TaskName `
        -Action $action `
        -Trigger $trigger `
        -Settings $settings `
        -Principal $principal `
        -Description 'OpenJarvis API server (loopback default — see deploy/windows/README.md)' | Out-Null

    if (-not (Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue)) {
        Write-Fail "Scheduled task '$TaskName' was not registered."
    }
    Write-Ok "Task '$TaskName' registered (least-privileged, loopback default)."
    Write-Info "It will start automatically at next logon. To start now: start"
}

# ---------------------------------------------------------------------------
# uninstall
# ---------------------------------------------------------------------------

function Uninstall-Task {
    $existing = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
    if (-not $existing) {
        Write-Warn2 "Task '$TaskName' is not registered — nothing to remove."
    } else {
        Write-Info "Stopping '$TaskName' (if running)..."
        Stop-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
        Write-Info "Unregistering '$TaskName'..."
        Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
        Write-Ok "Task '$TaskName' removed."
    }

    # These two files are generated by this script, not user data. Removing
    # them avoids leaving a stale credential behind. Other configuration and
    # user data under the install root are left untouched.
    $paths = Get-ServicePaths (Get-DefaultInstallRoot)
    foreach ($generated in @($paths.KeyFile, $paths.Launcher)) {
        if (Test-Path -LiteralPath $generated) {
            Remove-Item -LiteralPath $generated -Force -ErrorAction SilentlyContinue
        }
    }
}

# ---------------------------------------------------------------------------
# start / stop / status
# ---------------------------------------------------------------------------

function Start-Task {
    if (-not (Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue)) {
        Write-Fail "Task '$TaskName' is not registered. Run 'install' first."
    }
    Start-ScheduledTask -TaskName $TaskName
    Write-Ok "Task '$TaskName' started."
}

function Stop-Task {
    if (-not (Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue)) {
        Write-Fail "Task '$TaskName' is not registered."
    }
    Stop-ScheduledTask -TaskName $TaskName
    Write-Ok "Task '$TaskName' stopped."
}

function Show-Status {
    $task = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
    if (-not $task) {
        Write-Host "Task '$TaskName' is not registered."
        Write-Host "Install it with:"
        Write-Host "  powershell -ExecutionPolicy RemoteSigned -File `"$PSCommandPath`" install"
        return
    }
    $info = Get-ScheduledTaskInfo -TaskName $TaskName
    Write-Host "Task    : $TaskName"
    Write-Host "State   : $($task.State)"
    Write-Host "LastRun : $($info.LastRunTime)"
    Write-Host "LastRes : 0x$('{0:X8}' -f $info.LastTaskResult)"
    Write-Host "NextRun : $($info.NextRunTime)"
}

# ---------------------------------------------------------------------------
# dispatch
# ---------------------------------------------------------------------------

switch ($Command) {
    'install'   { Install-Task }
    'uninstall' { Uninstall-Task }
    'status'    { Show-Status }
    'start'     { Start-Task }
    'stop'      { Stop-Task }
}
